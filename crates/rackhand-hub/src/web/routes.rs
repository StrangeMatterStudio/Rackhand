#[derive(Debug, Clone)]
pub struct RouteSpec {
    pub method: Method,
    pub path: &'static str,
    pub access: Access,
    pub page: Page,
}

const fn r(method: Method, path: &'static str, access: Access, page: Page) -> RouteSpec {
    RouteSpec { method, path, access, page }
}

